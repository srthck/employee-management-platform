export class StatutoryWageError extends Error {
  constructor(code, message, details = undefined) {
    super(`${code}: ${message}`);
    this.name = 'StatutoryWageError';
    this.code = code;
    if (details !== undefined) this.details = details;
  }
}

export const fail = (code, message, details) => {
  throw new StatutoryWageError(code, message, details);
};
